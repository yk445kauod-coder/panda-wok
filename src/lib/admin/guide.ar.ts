/**
 * Returns the guide in the requested language. The English source stays the
 * single definition of structure (ids, icons, capabilities, order); only the
 * copy is swapped, and any id missing from the Arabic overlay falls back to
 * English rather than rendering an empty card.
 */
export function localiseGuideSections(
  sections: readonly GuideSection[],
  locale: string,
): GuideSection[] {
  if (locale !== "ar") return sections as GuideSection[];
  return sections.map((section) => {
    const copy = GUIDE_AR_COPY[section.id];
    if (!copy) return section;
    return {
      ...section,
      title: copy.title,
      intro: copy.intro,
      topics: section.topics.map((topic) => {
        const t = copy.topics[topic.id];
        if (!t) return topic;
        return {
          ...topic,
          title: t.title,
          summary: t.summary,
          steps: t.steps,
          tips: t.tips,
        };
      }),
    };
  });
}

