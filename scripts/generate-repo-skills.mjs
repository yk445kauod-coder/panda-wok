#!/usr/bin/env node
/**
 * Generates src/lib/agent/repo-skills.generated.ts from the repo's markdown
 * skill sources.
 *
 * Why a generated module instead of reading the files at runtime: the app runs on
 * Cloudflare Workers, where there is no filesystem. The text has to be part of
 * the bundle. Generating it (rather than hand-copying it) keeps skills.md and
 * AGENTS.md as the single source of truth, so the agent instructions cannot drift
 * from what the repository actually documents.
 *
 * Runs from `prebuild`, `predev` and `pretypecheck`, so a stale bundle is not
 * possible.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const sources = [
  { name: "repo:skills.md", file: "skills.md", source: "repo" },
  { name: "repo:AGENTS.md", file: "AGENTS.md", source: "agents_md" },
];

const entries = [];
for (const source of sources) {
  const path = resolve(root, source.file);
  if (!existsSync(path)) continue;
  const text = readFileSync(path, "utf8");
  entries.push({ ...source, text });
}

const body = entries
  .map(
    (entry) =>
      `  { name: ${JSON.stringify(entry.name)}, source: ${JSON.stringify(entry.source)}, text: ${JSON.stringify(entry.text)} },`,
  )
  .join("\n");

const output = `// AUTO-GENERATED by scripts/generate-repo-skills.mjs — do not edit by hand.
// Source of truth: skills.md and AGENTS.md.

export type RepoSkillSource = { name: string; source: string; text: string };

export const REPO_SKILL_SOURCES: RepoSkillSource[] = [
${body}
];
`;

writeFileSync(resolve(root, "src/lib/agent/repo-skills.generated.ts"), output);
console.log(`generate-repo-skills: wrote ${entries.length} source(s)`);
